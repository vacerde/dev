#!/usr/bin/env node

import nodemailer from 'nodemailer';
import inquirer from 'inquirer';
import chalk from 'chalk';
import ora from 'ora';
import figlet from 'figlet';
import { createInterface } from 'readline';

// ─── Theme ────────────────────────────────────────────────────────────────────
const theme = {
  primary:   chalk.hex('#00D9FF'),
  secondary: chalk.hex('#FF6B35'),
  success:   chalk.hex('#00FF88'),
  error:     chalk.hex('#FF3366'),
  muted:     chalk.hex('#555577'),
  label:     chalk.hex('#AAAACC').bold,
  value:     chalk.hex('#FFFFFF'),
  border:    chalk.hex('#333355'),
};

// ─── Helpers ──────────────────────────────────────────────────────────────────
function banner() {
  console.clear();
  const art = figlet.textSync('SMTP  Tester', { font: 'Slant' });
  console.log(theme.primary(art));
  console.log(theme.muted('  ─────────────────────────────────────────────────────'));
  console.log(theme.muted('  Advanced SMTP diagnostic & test-mail tool · v1.0.0'));
  console.log(theme.muted('  ─────────────────────────────────────────────────────\n'));
}

function sectionHeader(title) {
  console.log('\n' + theme.primary('  ┌─ ') + theme.label(title));
  console.log(theme.primary('  │'));
}

function sectionEnd() {
  console.log(theme.primary('  └────────────────────────────────────\n'));
}

function printSummary(cfg) {
  console.log('\n' + theme.border('  ╔══════════════════════════════════════════╗'));
  console.log(    theme.border('  ║') + theme.primary.bold('       CONNECTION SUMMARY                 ') + theme.border('║'));
  console.log(    theme.border('  ╠══════════════════════════════════════════╣'));

  const row = (k, v) =>
    console.log(theme.border('  ║  ') + theme.label(k.padEnd(14)) + theme.value(String(v).padEnd(28)) + theme.border('║'));

  row('Host',     cfg.host);
  row('Port',     cfg.port);
  row('Security', cfg.security);
  row('User',     cfg.user);
  row('Pass',     '*'.repeat(Math.min(cfg.pass.length, 12)));
  row('From',     cfg.from);
  row('To',       cfg.to);
  row('Subject',  cfg.subject.slice(0, 26) + (cfg.subject.length > 26 ? '…' : ''));

  console.log(theme.border('  ╚══════════════════════════════════════════╝\n'));
}

function buildTransport(cfg) {
  const secure = cfg.security === 'SSL/TLS';
  const starttls = cfg.security === 'STARTTLS';

  return nodemailer.createTransport({
    host: cfg.host,
    port: Number(cfg.port),
    secure,
    auth: { user: cfg.user, pass: cfg.pass },
    tls: {
      rejectUnauthorized: cfg.rejectUnauthorized,
      ...(starttls ? {} : {}),
    },
    requireTLS: starttls,
    connectionTimeout: cfg.timeout * 1000,
    greetingTimeout:   cfg.timeout * 1000,
    socketTimeout:     cfg.timeout * 1000,
  });
}

