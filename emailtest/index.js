// ─── Main ─────────────────────────────────────────────────────────────────────
async function main() {
  banner();

  // ── SMTP Server ──────────────────────────────────────────────────────────────
  sectionHeader('SMTP SERVER');
  const server = await inquirer.prompt([
    {
      type: 'input',
      name: 'host',
      prefix: theme.primary('  │'),
      message: theme.label('Hostname  '),
      default: 'smtp.gmail.com',
      validate: v => v.trim() ? true : 'Host is required',
    },
    {
      type: 'list',
      name: 'security',
      prefix: theme.primary('  │'),
      message: theme.label('Security  '),
      choices: ['SSL/TLS', 'STARTTLS', 'None'],
      default: 'SSL/TLS',
    },
    {
      type: 'input',
      name: 'port',
      prefix: theme.primary('  │'),
      message: theme.label('Port      '),
      default: ans => ans.security === 'SSL/TLS' ? '465' : ans.security === 'STARTTLS' ? '587' : '25',
      validate: v => /^\d+$/.test(v) && +v > 0 && +v < 65536 ? true : 'Enter a valid port (1–65535)',
    },
    {
      type: 'confirm',
      name: 'rejectUnauthorized',
      prefix: theme.primary('  │'),
      message: theme.label('Verify TLS cert'),
      default: true,
    },
    {
      type: 'number',
      name: 'timeout',
      prefix: theme.primary('  │'),
      message: theme.label('Timeout (s)'),
      default: 15,
      validate: v => v > 0 ? true : 'Must be > 0',
    },
  ]);
  sectionEnd();

  // ── Credentials ──────────────────────────────────────────────────────────────
  sectionHeader('CREDENTIALS');
  const creds = await inquirer.prompt([
    {
      type: 'input',
      name: 'user',
      prefix: theme.primary('  │'),
      message: theme.label('Username  '),
      validate: v => v.trim() ? true : 'Username required',
    },
    {
      type: 'password',
      name: 'pass',
      prefix: theme.primary('  │'),
      message: theme.label('Password  '),
      mask: '●',
      validate: v => v.trim() ? true : 'Password required',
    },
  ]);
  sectionEnd();

  // ── Email ─────────────────────────────────────────────────────────────────────
  sectionHeader('EMAIL');
  const mail = await inquirer.prompt([
    {
      type: 'input',
      name: 'from',
      prefix: theme.primary('  │'),
      message: theme.label('From      '),
      default: creds.user,
      validate: v => /.+@.+\..+/.test(v) ? true : 'Enter a valid email',
    },
    {
      type: 'input',
      name: 'to',
      prefix: theme.primary('  │'),
      message: theme.label('To        '),
      validate: v => /.+@.+\..+/.test(v) ? true : 'Enter a valid email',
    },
    {
      type: 'input',
      name: 'subject',
      prefix: theme.primary('  │'),
      message: theme.label('Subject   '),
      default: `SMTP Test · ${new Date().toLocaleString()}`,
    },
    {
      type: 'list',
      name: 'bodyType',
      prefix: theme.primary('  │'),
      message: theme.label('Body type '),
      choices: ['HTML (styled)', 'Plain text'],
      default: 'HTML (styled)',
    },
    {
      type: 'input',
      name: 'customText',
      prefix: theme.primary('  │'),
      message: theme.label('Custom msg'),
      default: '',
      when: ans => ans.bodyType === 'Plain text',
    },
  ]);
  sectionEnd();

  // ── Summary & Confirm ─────────────────────────────────────────────────────────
  const cfg = { ...server, ...creds, ...mail };
  printSummary(cfg);

  const { confirmed } = await inquirer.prompt([{
    type: 'confirm',
    name: 'confirmed',
    prefix: theme.secondary('  ►'),
    message: theme.secondary.bold('Send test email now?'),
    default: true,
  }]);

  if (!confirmed) {
    console.log('\n' + theme.muted('  Aborted. No email sent.\n'));
    process.exit(0);
  }

  // ── Send ──────────────────────────────────────────────────────────────────────
  console.log();
  const transport = buildTransport(cfg);

  // Step 1: verify connection
  const spinVerify = ora({
    text: theme.primary('Connecting to SMTP server…'),
    spinner: 'dots12',
    color: 'cyan',
    prefixText: '  ',
  }).start();

  try {
    await transport.verify();
    spinVerify.succeed(theme.success('Connection verified ✓'));
  } catch (err) {
    spinVerify.fail(theme.error('Connection failed ✗'));
    console.log('\n' + theme.error('  Error: ') + theme.value(err.message));
    if (err.code) console.log(theme.muted('  Code:  ') + err.code);
    if (err.response) console.log(theme.muted('  SMTP:  ') + err.response);
    console.log();
    process.exit(1);
  }

  // Step 2: send
  const spinSend = ora({
    text: theme.primary('Sending email…'),
    spinner: 'dots12',
    color: 'cyan',
    prefixText: '  ',
  }).start();

  try {
    const isHtml = cfg.bodyType === 'HTML (styled)';
    const info = await transport.sendMail({
      from: cfg.from,
      to: cfg.to,
      subject: cfg.subject,
      ...(isHtml
        ? { html: buildHtmlBody(cfg), text: 'SMTP test successful.' }
        : { text: cfg.customText || 'SMTP test successful.' }),
    });

    spinSend.succeed(theme.success('Email sent successfully ✓'));

    console.log('\n' + theme.border('  ┌──────────────────────────────────────────┐'));
    console.log(    theme.border('  │') + theme.success.bold('  ✓ DELIVERY REPORT                        ') + theme.border('│'));
    console.log(    theme.border('  ├──────────────────────────────────────────┤'));

    const dRow = (k, v) =>
      console.log(theme.border('  │  ') + theme.label(k.padEnd(14)) + theme.value(String(v || '—').slice(0, 28).padEnd(28)) + theme.border('│'));

    dRow('Message ID', info.messageId);
    dRow('Response',   info.response);
    dRow('Accepted',   info.accepted?.join(', '));
    if (info.rejected?.length) dRow('Rejected', info.rejected.join(', '));

    console.log(theme.border('  └──────────────────────────────────────────┘\n'));

  } catch (err) {
    spinSend.fail(theme.error('Send failed ✗'));
    console.log('\n' + theme.error('  Error: ') + theme.value(err.message));
    if (err.responseCode) console.log(theme.muted('  Code:  ') + err.responseCode);
    if (err.response)     console.log(theme.muted('  SMTP:  ') + err.response);
    console.log();
    process.exit(1);
  }

  // ── Run again? ────────────────────────────────────────────────────────────────
  const { again } = await inquirer.prompt([{
    type: 'confirm',
    name: 'again',
    prefix: theme.muted('  ►'),
    message: theme.muted('Run another test?'),
    default: false,
  }]);

  if (again) {
    await main();
  } else {
    console.log(theme.muted('\n  Bye! 👋\n'));
  }
}

main().catch(err => {
  console.error(theme.error('\n  Fatal: ') + err.message);
  process.exit(1);
});